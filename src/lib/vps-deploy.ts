export function generateDeployScript(cfg: VpsDeployConfig): string {
  const panel = cfg.panel
  const port = panelPort(cfg)
  const pw = cfg.adminPassword || 'changeme'
  return `#!/bin/bash
# miliconfig — ${panel.name} one-click deploy
# Run this on your VPS: bash deploy.sh

set -e

echo "🚀 Deploying ${panel.name}..."

# 1. Create directories
mkdir -p panel-data certbot/conf certbot/www${panel.requiresDb === 'postgres' ? ' db-data' : ''}${panel.requiresRedis ? ' redis-data' : ''}

# 2. Build and start services
echo "🐳 Building and starting Docker containers..."
docker compose up -d --build

echo ""
echo "✅ ${panel.name} is running!"
echo "   HTTP:  http://YOUR_SERVER_IP:${port}"
echo "   Panel: http://YOUR_SERVER_IP:${port}${panel.panelPath}"
${panel.defaultAdminPassword ? `echo "   Default login: admin / ${panel.defaultAdminPassword}"\n` : ''}echo "   Password: ${pw}"
${panel.requiresDb === 'postgres' ? 'echo "   DB:    PostgreSQL sidecar (user: panel, db: panel)"\n' : ''}${panel.requiresRedis ? 'echo "   Cache: Redis sidecar"\n' : ''}echo ""
echo "To set up HTTPS:"
echo "  1. Point your domain DNS to this server"
echo "  2. Edit .env and set PUBLIC_DOMAIN=your.domain.com"
echo "  3. Run: docker compose --profile certonly run --rm certbot certonly --webroot -w /var/www/certbot -d your.domain.com"
echo "  4. Uncomment the HTTPS server block in nginx.conf"
echo "  5. Run: docker compose restart nginx"
`
}
