// ── Railway deployment ────────────────────────────────────────────────────────

export function generateRailwayDockerfile(cfg: VpsDeployConfig): string {
  return generateDockerfile(cfg)
}

export function generateRailwayToml(cfg: VpsDeployConfig): string {
  const panel = cfg.panel
  const start = panel.startCommand ?? 'python main.py'
  const envLines = panelEnv(cfg).map(([k, v]) => `${k} = "${v}"`).join('\n')
  return `# miliconfig — Railway deploy config for ${panel.name}
# Generated by miliconfigpro panel

[build]
dockerfilePath = "Dockerfile"

[deploy]
startCommand = "${start}"
healthcheckPath = "${panel.healthPath ?? panel.panelPath}"
healthcheckTimeout = 30
restartPolicyType = "on_failure"
restartPolicyMaxRetries = 5

[deploy.env]
${envLines}
`
}

